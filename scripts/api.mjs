// Writes kit/API.md: a compact reference of every exported helper in kit/scripts/lib/reel-lib.cjs and every timeline
// helper available inside a scene's anim (HELPERS), built from the comments above each declaration. Read API.md while
// building scenes instead of the whole lib; open the lib or kit/examples/ only for the one piece you're reusing.
// Usage: node api.mjs [--check]   (--check exits 1 when API.md is out of date with the lib; setup.mjs runs it)
// Run it after any change to the kit lib (SKILL.md rule 8).
import fs from "node:fs";
import path from "node:path";
import { SKILL, ok, fail } from "./_common.mjs";

const LIB = path.join(SKILL, "kit/scripts/lib/reel-lib.cjs"), OUT = path.join(SKILL, "kit/API.md");
const src = fs.readFileSync(LIB, "utf8").replace(/\r\n/g, "\n").split("\n");

// exported names (module.exports = { ... } plus any Object.assign(module.exports, { ... }))
const text = src.join("\n");
const exported = new Set();
for (const m of text.matchAll(/module\.exports(?:\s*=\s*|,\s*)\{([^}]*)\}/g)) m[1].split(/[\s,]+/).filter(Boolean).forEach((n) => exported.add(n));

const sig = (line) => {
  let m = line.match(/^function (\w+)\(([^)]*)\)/);
  if (m) return [m[1], m[2]];
  m = line.match(/^const (\w+) = (?:\(([^)]*)\)|(\w+)) =>/);
  if (m) return [m[1], m[2] != null ? m[2] : m[3]];
  m = line.match(/^const (\w+) =/);
  return m ? [m[1], null] : null;
};
// a "// ids: ... · starts: ..." line is kept apart (meta): the ids a builder creates and its state before any tween
const commentAbove = (i, indent = "") => {
  const out = [];
  for (let k = i - 1; k >= 0 && src[k].startsWith(indent + "//") && !/^\s*\/\/ -{3,}/.test(src[k]); k--) out.unshift(src[k].slice(indent.length + 2).trim());
  const meta = out.filter((l) => /^(ids|starts):/.test(l)), doc = out.filter((l) => !/^(ids|starts):/.test(l));
  return { doc: doc.join(" ").replace(/\s+/g, " "), meta: meta.join(" ").replace(/\s+/g, " ") };
};

// timeline internals that scenes never call directly, and the iso.js re-exports (described by hand below)
const INTERNAL = new Set(["q", "bz", "mfV"]);
const ISO = new Set(["T", "C", "S", "make", "tube", "arrow", "leader", "check"]);
const sections = [], seen = new Set();
let cur = { title: "Basics", items: [] };
sections.push(cur);
let inHelpers = false;
const helpers = [];
src.forEach((line, i) => {
  if (/^const HELPERS = `/.test(line)) { inHelpers = true; return; }
  if (inHelpers) {
    if (/^\s*};?`;\s*$/.test(line) || /`;\s*$/.test(line) && !/=>/.test(line)) { inHelpers = false; return; }
    const m = line.match(/^(\s+)const (\w+) = (?:\(([^)]*)\)|(\w+)) =>/);
    if (m && !INTERNAL.has(m[2])) {
      const name = m[2], params = m[3] != null ? m[3] : m[4];
      helpers.push({ name, params, ...commentAbove(i, m[1]) });
    }
    return;
  }
  const h = line.match(/^\/\/ -{3,} (.+?) -{3,}\s*$/);
  if (h) { cur = { title: h[1], items: [] }; sections.push(cur); return; }
  const s = sig(line);
  if (!s || !exported.has(s[0]) || seen.has(s[0])) return;
  seen.add(s[0]);
  cur.items.push({ name: s[0], params: s[1], ...commentAbove(i) });
});

// the scene shell's CSS classes (from const CSS): selector + its /* comment */, so scenes can use them without opening the lib
const css = [];
let inCss = false;
for (const line of src) {
  if (/^const CSS = `/.test(line)) { inCss = true; continue; }
  if (!inCss) continue;
  if (/^`;/.test(line)) break;
  const m = line.match(/^\s*([.#][^{@]*?)\s*\{.*\}\s*(?:\/\*\s*(.*?)\s*\*\/)?\s*$/);
  if (m && /^\./.test(m[1]) && m[2]) css.push({ sel: m[1], doc: m[2] });   // undocumented rules are shell internals
}

const fmt = (it) => `- \`${it.name}${it.params != null ? `(${it.params.replace(/\s+/g, " ")})` : ""}\`${it.doc ? ` ${it.doc}` : ""}` +
  (it.meta ? `\n  - ${it.meta}` : "");
const missing = [...exported].filter((n) => !seen.has(n) && !ISO.has(n)).sort();
const md = [
  "# Kit API (generated by scripts/api.mjs from kit/scripts/lib/reel-lib.cjs; don't edit by hand)",
  "",
  "Scene files: `module.exports = (L, s, reel) => ({ lift, svg, html, anim, over?, cam?, fade?, boxes?, overlapOk? })`.",
  "`s` = `{ id, p, n, line, start, dur, words, at(word, nth) }`; every cue time comes from `s.at()` (script/cues.md lists them).",
  "Prefix every id with `s.p`. `boxes: [{ id, r: [x, y, w, h], t?: [t0, t1] }]` (in .lift coords) are checked by build-scenes",
  "for overlaps and for leaving the grid field; duplicate ids fail the build. DESIGN.md says how things look, this file what exists.",
  "",
  "## Timeline helpers (inside a scene's `anim`, which runs with `tl`, `q`, `E`, `gsap` in scope)",
  "",
  ...helpers.map(fmt),
  "",
  ...sections.filter((s) => s.items.length).flatMap((s) => [`## ${s.title}`, "", ...s.items.map(fmt), ""]),
  "## CSS classes (the scene shell's stylesheet, usable in any scene's html)",
  "",
  ...css.map((c) => `- \`${c.sel}\`${c.doc ? ` ${c.doc}` : ""}`),
  "",
  "## From assets/js/iso.js (re-exported)",
  "",
  "- `T` the colour tokens (DESIGN.md 2): never hard-code a hex in a scene. `C`, `S` = cos 30 and sin 30.",
  "- `make(ox, oy)` the 30-degree projector: `{ P(x, y, z), poly, quad, line, box(x, y, z, w, d, h, { top, left, right, sw }), face, topFace, yFace, xFace, disc, knob }`. x runs down-right, y down-left, z up; the face functions give an SVG transform for drawing flat on a face.",
  "- `tube(d, { w, fill })` double-line cable; `arrow(x, y, len, angle, fill)` block arrow; `leader(points)` a static leader; `check(x, y, s, sw)` a check mark.",
  "",
  ...(missing.length ? ["## Also exported", "", missing.map((n) => `\`${n}\``).join(", "), ""] : []),
].join("\n");

if (process.argv.includes("--check")) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (now !== md) fail(`kit/API.md is out of date with the kit lib. Run: node "${path.join(SKILL, "scripts/api.mjs")}"`);
  ok("kit/API.md matches the kit lib");
} else {
  fs.writeFileSync(OUT, md);
  ok(`kit/API.md: ${helpers.length} timeline helpers, ${seen.size} lib exports (${md.split("\n").length} lines)`);
}

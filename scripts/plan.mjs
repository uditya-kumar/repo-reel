// Step 6a. Write the cut-plan stub scripts/scenes/_plan.cjs from script/timing.json (the last step of audio.mjs).
// Usage: node plan.mjs <projectDir> [--force]
// The stub calls L.plan() (kit lib), which holds the v4 machinery: start/dur per key, the beat grid, toScreen rects,
// handoffs with beat-snapped landings, hold-cut asserts, cam() and side(). The reel only fills in data: lifts,
// camera ends, the rects R the cuts connect, hands and holds. An existing _plan.cjs is never overwritten without --force.
import fs from "node:fs";
import path from "node:path";
import { projectDir, need, rd, ok } from "./_common.mjs";

const dir = projectDir(process.argv[2]);
const T = rd(need(path.join(dir, "script/timing.json"), "run timing.mjs first"));
const out = path.join(dir, "scripts/scenes/_plan.cjs");
if (fs.existsSync(out) && !process.argv.includes("--force")) {
  ok(`scripts/scenes/_plan.cjs exists, left as it is (--force rewrites it)`);
  process.exit(0);
}
const keys = T.scenes.map((s) => s.line), w = Math.max(...keys.map((k) => k.length));
const pad = (k) => `${k}:`.padEnd(w + 2);
const src = `// Shared cut plan: every scene's lift and camera end, the rects the match cuts connect, and the handoffs, so both
// sides of every cut read the same numbers. Generated by plan.mjs from script/timing.json; edit freely (L.plan in the
// kit lib documents every key). Plan the cuts once timing.json exists; rebuild them if the timing changes.
//   scene          key        start    dur
${T.scenes.map((s) => `//   ${s.id.padEnd(14)} ${s.line.padEnd(w)}  ${s.start.toFixed(2).padStart(6)}  +${s.dur.toFixed(2)}`).join("\n")}
const L = require("../lib/reel-lib.cjs");
const timing = require("../../script/timing.json");

const P = L.plan(timing, {
  // vertical offset that centres each scene's art in the grid field (DESIGN.md 4)
  lift: { ${keys.map((k) => `${k}: 0`).join(", ")} },
  // where each scene's camera ends up (it eases there from its landing within L.SETTLE and holds); hold-cut sources end at { s: 1 }
  camEnd: {
${keys.map((k) => `    ${pad(k)} { s: 1.03, x: 0, y: -8 },`).join("\n")}
  },
  // rects [x, y, w, h] in each scene's .lift that the cuts connect, e.g. hookWin: [300, 420, 540, 280]
  R: {},
  // match cuts: name: [from, to, rectA, rectB, t0, land]. cut = to's start (above); land snaps to the nearest beat
  // (script/cues.md lists them); keep each side 0.23-0.5 s and the cut near peak speed (f 0.35-0.6)
  hands: {},
  // hold cuts (the same frame on both sides): [[from, to]]
  holds: [],
});

// reel-specific shared numbers (implode seeds, shared geometry) go next to the plan
module.exports = { ...P };
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, src);
ok(`scripts/scenes/_plan.cjs: plan stub for ${keys.length} scenes (${keys.join(", ")})`);
